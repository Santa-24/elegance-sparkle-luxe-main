create or replace view public.upcoming_bookings as
select
  b.id,
  b.booking_code,
  b.customer_name,
  b.phone,
  b.email,
  b.service_name,
  b.booking_date,
  b.booking_time,
  b.duration_minutes,
  b.status,
  b.source,
  cp.preferred_contact_method,
  s.duration_label,
  s.category
from public.bookings b
left join public.customer_preferences cp on b.phone = cp.customer_phone
left join public.services s on b.service_id = s.id
where b.deleted_at is null
  and b.booking_date >= current_date
  and b.status not in ('rejected', 'cancelled')
order by b.booking_date, b.booking_time;

create or replace view public.booking_stats as
select 'Total Bookings' as metric, count(*) as value
from public.bookings
where deleted_at is null
union all
select 'Approved Bookings', count(*)
from public.bookings
where deleted_at is null and status = 'approved'
union all
select 'Pending Bookings', count(*)
from public.bookings
where deleted_at is null and status = 'pending'
union all
select 'Unique Customers', count(distinct phone)
from public.bookings
where deleted_at is null
union all
select 'Total Revenue', coalesce(sum(amount_paid), 0)::bigint
from public.bookings
where deleted_at is null and status = 'completed';

create or replace view public.service_popularity as
select
  s.id,
  s.title,
  s.category,
  count(b.id) as booking_count,
  count(b.id) * 100.0 / nullif(sum(count(b.id)) over (), 0) as percentage,
  coalesce(sum(b.amount_paid), 0) as revenue_generated
from public.services s
left join public.bookings b
  on s.id = b.service_id and b.deleted_at is null
where s.deleted_at is null
group by s.id, s.title, s.category
order by booking_count desc;

