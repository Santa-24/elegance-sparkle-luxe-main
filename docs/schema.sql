create or replace view public.revenue_summary as
select
  b.booking_date,
  count(*) as booking_count,
  coalesce(sum(b.amount_quoted), 0) as quoted_amount,
  coalesce(sum(b.amount_paid), 0) as received_amount,
  coalesce(sum(coalesce(b.amount_quoted, 0) - coalesce(b.amount_paid, 0)), 0) as pending_amount,
  count(*) filter (where b.payment_status = 'paid') as paid_count,
  count(*) filter (where b.payment_status = 'unpaid') as unpaid_count
from public.bookings b
where b.deleted_at is null and b.status = 'completed'
group by b.booking_date
order by b.booking_date desc;

